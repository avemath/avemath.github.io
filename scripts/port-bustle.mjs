// Compiles the vendored Grace Mae bustle drawing (vendor/gracemae) to plain JavaScript for the
// home page's live version: type-only imports drop out and JSX becomes calls to src/lib/svg-h.ts,
// under names the drawing's own variables (it has an `h` for heights) can't shadow.
// Run with `node scripts/port-bustle.mjs` after updating the vendored copy.
import { readFileSync, writeFileSync } from 'node:fs';
import { transformSync } from 'esbuild';

const src = readFileSync(new URL('../vendor/gracemae/bustleDrawing.tsx.txt', import.meta.url), 'utf8');
const { code } = transformSync(src, { loader: 'tsx', jsxFactory: 'svgH', jsxFragment: 'SvgFragment', format: 'esm', legalComments: 'none' });
const head = `// Generated by scripts/port-bustle.mjs from vendor/gracemae/bustleDrawing.tsx.txt. Do not edit.\n// @ts-nocheck\nimport { h as svgH, Fragment as SvgFragment } from './svg-h';\n`;
writeFileSync(new URL('../src/lib/bustle-drawing.js', import.meta.url), head + code);
console.log('Wrote src/lib/bustle-drawing.js');
